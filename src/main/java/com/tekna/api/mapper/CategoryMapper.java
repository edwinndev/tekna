package com.tekna.api.mapper;

import com.tekna.api.dto.CategoryOutput;
import com.tekna.api.dto.CreateCategoryInput;
import com.tekna.api.dto.UpdateCategoryInput;
import com.tekna.api.entity.Category;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;

import java.util.List;

@Mapper(componentModel = "spring")
public interface CategoryMapper {

    @Mapping(target = "id", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "deletedAt", ignore = true)
    @Mapping(target = "deletedBy", ignore = true)
    Category toEntity(CreateCategoryInput input);

    CategoryOutput toOutput(Category entity);

    List<CategoryOutput> toOutputList(List<Category> entities);

    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "deletedAt", ignore = true)
    @Mapping(target = "deletedBy", ignore = true)
    void updateEntityFromInput(UpdateCategoryInput input, @MappingTarget Category entity);
}
